%ocuduPUSCHAnalyzer Analyzes a PUSCH transmission from a resource grid.
%   ocuduPUSCHAnalyzer(CARRIER, PUSCH, EXTRA, RGFILENAME, RGOFFSET, RGSIZE) analyzes the
%   NR Physical Uplink Shared Channel transmission detailed by the carrier
%   configuration CARRIER, by the shared channel configuration PUSCH and by the
%   content of the EXTRA struct, as returned by ocuduParseLogs, with fields
%      RV                   - Redundancy version.
%      TargetCodeRate       - Target code rate.
%      TransportBlockLength - Transport block size in bits.
%      OACK, OCSI1          - Number of multiplexed HARQ-ACK and CSI Part 1 bits.
%      DCPosition           - DC subcarrier index (empty if unknown). The DC RE is
%                             removed from the grid before equalization.
%      TBSLBRM              - Limited buffer rate matching TBS in bytes (empty if
%                             unknown, in which case the buffer is not limited).
%   The resource grid IQ samples are stored in the binary file RGFILENAME. RGOFFSET
%   and RGSIZE are the offset and size, as a number of single-precision complex
%   floating point numbers, of the slot containing the PUSCH transmission inside the
%   binary file.
%
%   The receiver is implemented with 5G Toolbox functions: channel estimation with
%   nrChannelEstimate, zero-forcing equalization, soft demodulation with the LLRs
%   weighted by the post-equalization channel state information, and UL-SCH and UCI
%   decoding. When called without output arguments, the function prints the CRC
%   status of the transport block and the decoded UCI bits.
%
%   [BITS, CRCOK, INFO] = ocuduPUSCHAnalyzer(...) returns the decoded transport block
%   BITS (int8 column vector, as nrULSCHDecoder), the transport block CRC status
%   CRCOK (true if OK) and the struct INFO with fields
%      H          - Channel estimate (subcarriers x symbols x ports x layers).
%      NoiseVar   - Estimated noise variance.
%      Equalized  - Equalized data symbols (REs x layers).
%      LLRs       - Codeword soft bits after descrambling and CSI weighting.
%      ACK, CSI1  - Decoded HARQ-ACK and CSI Part 1 bits (empty if not multiplexed).
%      ACKCRCOK, CSI1CRCOK - UCI CRC status (empty if not multiplexed or if the
%                   payload has no CRC).
%
%   [...] = ocuduPUSCHAnalyzer(..., Plot=false) skips the figures (default true).
%
%   Example (interactive):
%   % Look for a PUSCH entry and the corresponding RX_SYMBOL line in the log file
%   % generated by the OCUDU gNB (PHY log level "debug"), e.g.
%   %    2026-11-13T14:05:08.494358 [PHY     ] [I] [   265.4] RX_SYMBOL: sector=0 offset=0 size=91728
%   %    2026-11-13T14:05:08.494420 [PHY     ] [D] [   265.4] PUSCH: rnti=0x4601 harq_id=0 ...
%   % and select the PUSCH entry when asked by ocuduParseLogs.
%   [carrier, pusch, extra] = ocuduParseLogs;
%   ocuduPUSCHAnalyzer(carrier, pusch, extra, 'rx_symbols.bin', 0, 91728)
%
%   See also ocuduParseLogs.

% SPDX-FileCopyrightText: Copyright (C) 2021-2026 Software Radio Systems Limited
% SPDX-License-Identifier: BSD-3-Clause-Open-MPI

function [bits, crcOK, info] = ocuduPUSCHAnalyzer(carrier, pusch, extra, rgFilename, rgOffset, rgSize, options)
    arguments
        carrier      (1, 1) nrCarrierConfig
        pusch        (1, 1) nrPUSCHConfig
        extra        (1, 1) struct
        rgFilename          {mustBeTextScalar, mustBeFile}
        rgOffset     (1, 1) double {mustBeInteger, mustBeNonnegative}
        rgSize       (1, 1) double {mustBeInteger, mustBePositive}
        options.Plot (1, 1) logical = true
    end

    import ocuduTest.helpers.readComplexFloatFile

    % Load the resource grid.
    nSubcarriers = carrier.NSizeGrid * 12;
    nSymbols = carrier.SymbolsPerSlot;
    nPorts = floor(rgSize / (nSubcarriers * nSymbols));

    assert((nSubcarriers * nSymbols * nPorts == rgSize), ['The dimensions of the resource grid ', ...
        '(%d x %d) are not consistent with the buffer size %d.'], nSubcarriers, nSymbols, rgSize);

    rxGrid = reshape(readComplexFloatFile(rgFilename, rgOffset, rgSize), ...
        [nSubcarriers, nSymbols, nPorts]);

    % Estimate the channel. With two CDM groups without data, the DM-RS is boosted by 3 dB.
    dmrsInd = nrPUSCHDMRSIndices(carrier, pusch);
    dmrsSym = nrPUSCHDMRS(carrier, pusch);

    if (pusch.DMRS.NumCDMGroupsWithoutData == 2)
        betaDMRS = sqrt(2);
    else
        betaDMRS = 1;
    end

    [H, noiseVar] = nrChannelEstimate(carrier, rxGrid, dmrsInd, dmrsSym * betaDMRS, ...
        CDMLengths=pusch.DMRS.CDMLengths);

    % Remove the DC from the grid, if its position is known.
    if ~isempty(extra.DCPosition)
        rxGrid(extra.DCPosition + 1, :, :) = 0;
    end

    % Zero-forcing equalization (nrEqualizeMMSE with zero noise variance). The CSI
    % output is the inverse of the post-equalization noise enhancement per RE and layer.
    [dataInd, puschInfo] = nrPUSCHIndices(carrier, pusch);
    [rxSym, Hest] = nrExtractResources(dataInd, rxGrid, H);
    [equalized, csi] = nrEqualizeMMSE(rxSym, Hest, 0);
    % A zero channel estimate (e.g., an all-zero grid) gives a non-finite CSI: no
    % channel, no information.
    csi(~isfinite(csi)) = 0;

    % Make sure the TBS is consistent.
    tbsCheck = nrTBS(pusch.Modulation, pusch.NumLayers, length(pusch.PRBSet), ...
        puschInfo.NREPerPRB, extra.TargetCodeRate);
    if (tbsCheck ~= extra.TransportBlockLength)
        error('Inconsistent configuration: the computed TBS is %d, the provided one is %d.', ...
            tbsCheck, extra.TransportBlockLength);
    end

    % Soft demodulation and descrambling.
    % The estimated noise variance can be exactly zero (e.g., with strongly quantized
    % or all-zero grids), which would give non-finite LLRs.
    llrs = nrPUSCHDecode(carrier, pusch, equalized, max(noiseVar, realmin('single')));

    % The codeword bits follow the layer-demapped order of the symbols (all layers of
    % the first RE, then all layers of the second RE, and so on).
    bps = ocuduLib.phy.helpers.ocuduGetBitsSymbol(pusch.Modulation);
    equalizedCW = nrLayerDemap(equalized);
    csiCW = nrLayerDemap(csi);

    % Make sure equalized zeros translate to soft zeros. This is especially important
    % for the REs that were nulled out to remove the DC from the grid.
    llrs(repelem(equalizedCW{1} == 0, bps)) = 0;

    % Weight the LLRs by the post-equalization CSI.
    llrs = llrs .* repelem(csiCW{1}, bps);

    % Demultiplex data and UCI.
    [culsch, cack, ccsi1] = nrULSCHDemultiplex(pusch, extra.TargetCodeRate, ...
        extra.TransportBlockLength, extra.OACK, extra.OCSI1, 0, llrs);

    % Decode data.
    ulschDecoder = nrULSCHDecoder( ...
        MultipleHARQProcesses=false, ...
        TargetCodeRate=extra.TargetCodeRate, ...
        TransportBlockLength=extra.TransportBlockLength);
    nref = computeNref(extra, nrULSCHInfo(pusch, extra.TargetCodeRate, extra.TransportBlockLength, ...
        extra.OACK, extra.OCSI1, 0).C);
    if (nref > 0)
        ulschDecoder.LimitedBufferRateRecovery = true;
        ulschDecoder.LimitedBufferSize = nref;
    end
    [bits, blkCRCErr] = ulschDecoder(culsch, pusch.Modulation, pusch.NumLayers, extra.RV);
    crcOK = ~blkCRCErr;

    % Decode UCI.
    [ack, ackCRCOK] = decodeUCI(cack, extra.OACK, pusch.Modulation);
    [csi1, csi1CRCOK] = decodeUCI(ccsi1, extra.OCSI1, pusch.Modulation);

    info = struct('H', H, 'NoiseVar', noiseVar, 'Equalized', equalized, 'LLRs', llrs, ...
        'ACK', ack, 'ACKCRCOK', ackCRCOK, 'CSI1', csi1, 'CSI1CRCOK', csi1CRCOK);

    if (nargout == 0)
        printResults(crcOK, ack, ackCRCOK, csi1, csi1CRCOK);
    end

    if options.Plot
        plotAnalysis(rxGrid, H, equalized, llrs, pusch.Modulation);
    end
end % of function ocuduPUSCHAnalyzer(...)

function nref = computeNref(extra, nCodeblocks)
% Limited buffer rate matching length per codeblock, as in OCUDU ldpc::compute_N_ref
% (zero means unlimited buffer).
    maxCodeblockSize = 25344;
    nref = 0;
    if (isfield(extra, 'TBSLBRM') && ~isempty(extra.TBSLBRM))
        nref = floor(extra.TBSLBRM * 8 * 3 / (2 * nCodeblocks));
        if (nref >= maxCodeblockSize)
            nref = 0;
        end
    end
end % of function computeNref(extra, nCodeblocks)

function [bits, crcOK] = decodeUCI(codeword, nBits, modulation)
% Decodes a multiplexed UCI field. Both outputs are empty if the field is not
% multiplexed, CRCOK is empty if the payload has no CRC.
    bits = [];
    crcOK = [];
    if isempty(codeword)
        return;
    end
    [bits, crcErr] = nrUCIDecode(codeword, nBits, modulation);
    if ~isempty(crcErr)
        crcOK = ~crcErr;
    end
end % of function decodeUCI(codeword, nBits, modulation)

function printResults(crcOK, ack, ackCRCOK, csi1, csi1CRCOK)
% Prints the CRC status of the transport block and the decoded UCI bits.
    fprintf('The block CRC is %s.\n', crcString(crcOK));
    printUCI('ACK', ack, ackCRCOK);
    printUCI('CSI1', csi1, csi1CRCOK);
end % of function printResults(...)

function printUCI(name, bits, crcOK)
% Prints a decoded UCI field, if present.
    if isempty(bits)
        return;
    end
    msg = sprintf('Multiplexed %s is %s', name, join(string(bits(:).')));
    if ~isempty(crcOK)
        msg = sprintf('%s (CRC is %s)', msg, crcString(crcOK));
    end
    fprintf('%s.\n', msg);
end % of function printUCI(name, bits, crcOK)

function s = crcString(crcOK)
% Converts a CRC status into "OK" or "KO".
    if crcOK
        s = 'OK';
    else
        s = 'KO';
    end
end % of function crcString(crcOK)

function plotAnalysis(rxGrid, H, equalized, llrs, modulation)
% Plots the resource grid amplitude, the channel estimate, the equalized
% constellation and the soft bit distribution.
    [nSubcarriers, nSymbols, nPorts] = size(rxGrid);
    nLayers = size(H, 4);
    [symbolIndices, subcIndices] = meshgrid(0:nSymbols - 1, 0:nSubcarriers - 1);

    % Resource grid amplitude, one tile per receive port.
    figure(Name='ocuduPUSCHAnalyzer: Resource grid amplitude');
    tiledlayout(nPorts, 1);
    for iPort = 1:nPorts
        nexttile;
        imagesc(0, 0, abs(rxGrid(:, :, iPort)));
        % By default, imagesc reverses the y axis.
        set(gca, 'YDir', 'normal');
        colorbar;
        xlabel('Symbol');
        ylabel('Subcarrier');
        title(sprintf('Rx port %d', iPort - 1));
    end

    % Channel estimate magnitude and phase, one row per receive port and layer.
    figure(Name='ocuduPUSCHAnalyzer: Channel estimate');
    tiledlayout(nPorts * nLayers, 2);
    for iPort = 1:nPorts
        for iLayer = 1:nLayers
            hPL = H(:, :, iPort, iLayer);
            label = sprintf('Rx port %d, layer %d', iPort - 1, iLayer - 1);

            nexttile;
            surf(symbolIndices, subcIndices, abs(hPL), 'LineStyle', 'none', 'FaceColor', 'flat');
            colorbar;
            xlabel('Symbol');
            ylabel('Subcarrier');
            zlabel('Magnitude');
            title([label, ': magnitude']);
            zmin = min(abs(hPL), [], 'all') * 0.9;
            zmax = max(abs(hPL), [], 'all') * 1.1;
            if (zmin == zmax)
                zmin = zmin - 0.5;
                zmax = zmax + 0.5;
            end
            axis([0, nSymbols - 1, 0, nSubcarriers - 1, zmin, zmax]);

            nexttile;
            surf(symbolIndices, subcIndices, angle(hPL), 'LineStyle', 'none', 'FaceColor', 'flat');
            colorbar;
            xlabel('Symbol');
            ylabel('Subcarrier');
            zlabel('Angle [rad]');
            title([label, ': phase']);
            axis([0, nSymbols - 1, 0, nSubcarriers - 1, -pi, pi]);
        end
    end

    % Equalized constellation (one tile per layer, with the ideal constellation
    % points) and soft bit distribution.
    bps = ocuduLib.phy.helpers.ocuduGetBitsSymbol(modulation);
    idealPoints = nrSymbolModulate(reshape(dec2bin(0:2^bps - 1, bps).' - '0', [], 1), modulation);
    axisLimit = 1.3 * max(abs(real(idealPoints)));

    figure(Name='ocuduPUSCHAnalyzer');
    tiledlayout('flow');
    for iLayer = 1:nLayers
        nexttile;
        layerSymbols = equalized(:, iLayer);
        % Skip the REs nulled out to remove the DC.
        layerSymbols = layerSymbols(layerSymbols ~= 0);
        scatter(real(layerSymbols), imag(layerSymbols), 2, 'filled', MarkerFaceAlpha=0.15);
        hold on;
        plot(real(idealPoints), imag(idealPoints), 'r.', MarkerSize=6);
        hold off;
        axis equal;
        axis([-axisLimit, axisLimit, -axisLimit, axisLimit]);
        grid on;
        xlabel('Real');
        ylabel('Imaginary');
        title(sprintf('Equalized constellation, layer %d (%s)', iLayer - 1, modulation));
    end

    nexttile([1, nLayers]);
    histogram(llrs, 'Normalization', 'pdf');
    grid on;
    xlabel('Soft bits');
    ylabel('Probability density');
    title('Received soft bit distribution');
end % of function plotAnalysis(rxGrid, H, equalized, llrs, modulation)
